"""Export the SQLAlchemy schema as a Supabase SQL migration without connecting."""
import importlib
import os
from pathlib import Path
import sys

from sqlalchemy import create_mock_engine

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
# This is an offline compiler. Ignore host database settings in this process.
os.environ.update(DATABASE_URL="sqlite+pysqlite://", JWT_SECRET_KEY="schema-export-only", ENVIRONMENT="test", STORAGE_BACKEND="local")
from database import Base  # noqa: E402

for model in ("user", "auth_session", "book", "book_copy", "book_interaction", "transaction", "reservation", "inventory_write", "entry_log", "face_embedding", "reading_goal", "library_settings", "notification", "password_reset", "security_alert"):
    importlib.import_module(f"models.{model}")


def generate() -> str:
    statements = []
    mock = create_mock_engine("postgresql://", lambda sql, *a, **kw: statements.append(str(sql.compile(dialect=mock.dialect)).strip() + ";"))
    Base.metadata.create_all(mock, checkfirst=False)
    for table in Base.metadata.sorted_tables:
        name = mock.dialect.identifier_preparer.quote(table.name)
        statements.extend([
            f"ALTER TABLE public.{name} ENABLE ROW LEVEL SECURITY;",
            f"REVOKE ALL ON TABLE public.{name} FROM anon, authenticated;",
        ])
    sql = "-- Generated by scripts/generate_supabase_schema.py.\n-- FastAPI owns authorization; browser roles have no direct table access.\n\n" + "\n\n".join(statements)
    return "\n".join(line.rstrip() for line in sql.splitlines()) + "\n"


if __name__ == "__main__":
    output = ROOT / "supabase" / "migrations" / "20261010000100_library_schema.sql"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(generate(), encoding="utf-8")
    print(f"Exported {len(Base.metadata.tables)} tables to {output.relative_to(ROOT)}.")
